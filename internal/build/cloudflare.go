// CloudflareWorker is the path, relative to the output folder, of the
// Cloudflare Pages advanced-mode worker written by --cloudflare-auth. Pages
// reads _worker.js from the deployed folder itself (Functions in functions/
// are read from the project root instead, so they would be lost when
// deploying the output folder from elsewhere).
const CloudflareWorker = "_worker.js"

// legacyMiddleware is where earlier versions wrote the gate; builds remove
// it silently. Drop this cleanup in a later version.
const legacyMiddleware = "functions/_middleware.js"

// workerJS is a Cloudflare Pages advanced-mode worker that puts HTTP Basic
// Auth in front of every request. The credentials come from the AUTH_USER and
// AUTH_PASSWORD secrets of the Pages project; a deploy without them answers
// 500 (fails closed). __REALM__ is replaced with a JS string literal.
const workerJS = `// Generated by touring-diary --cloudflare-auth. Do not edit: the next build
// overwrites it. Cloudflare Pages runs this worker (advanced mode) for every
// request; it requires HTTP Basic Auth and then serves the static files. Set the credentials as secrets of the Pages
// project: AUTH_USER and AUTH_PASSWORD. Without them every request gets a 500.

const REALM = __REALM__;

export default {
  async fetch(request, env) {
    return handle(request, env);
  },
};

async function handle(request, env) {
  for (const name of ["AUTH_USER", "AUTH_PASSWORD"]) {
    if (typeof env[name] !== "string" || env[name] === "") {
      return new Response("Site misconfigured: the " + name + " secret is not set.\n", {
        status: 500,
        headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store" },
      });
    }
  }
  const creds = parseBasicAuth(request.headers.get("Authorization"));
  if (creds !== null) {
    // Compare both so the time does not reveal which one was wrong.
    const userOK = timingSafeEqual(creds.user, env.AUTH_USER);
    const passwordOK = timingSafeEqual(creds.password, env.AUTH_PASSWORD);
    if (userOK && passwordOK) {
      return env.ASSETS.fetch(request);
    }
  }
  return new Response("Authentication required.\n", {
    status: 401,
    headers: {
      "WWW-Authenticate": 'Basic realm="' + REALM + '", charset="UTF-8"',
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "no-store",
    },
  });
}

// parseBasicAuth returns {user, password} from an "Authorization: Basic ..."
// header, decoding the credentials as UTF-8, or null.
function parseBasicAuth(header) {
  if (!header) {
    return null;
  }
  const match = /^Basic[ \t]+([A-Za-z0-9+/=]+)[ \t]*$/i.exec(header);
  if (match === null) {
    return null;
  }
  let text;
  try {
    const binary = atob(match[1]);
    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return null;
  }
  const colon = text.indexOf(":");
  if (colon < 0) {
    return null;
  }
  return { user: text.slice(0, colon), password: text.slice(colon + 1) };
}

// timingSafeEqual compares the UTF-8 bytes of a and b in time that depends
// only on the longer length.
function timingSafeEqual(a, b) {
  const encoder = new TextEncoder();
  const x = encoder.encode(a);
  const y = encoder.encode(b);
  const n = Math.max(x.length, y.length);
  let diff = x.length ^ y.length;
  for (let i = 0; i < n; i++) {
    diff |= (i < x.length ? x[i] : 0) ^ (i < y.length ? y[i] : 0);
  }
  return diff === 0;
}
`

// workerSource returns the worker with the realm set to the trip
// title, cleaned for a quoted header value.
func workerSource(title string) string {
	realm := strings.Map(func(r rune) rune {
		switch {
		case r == '"' || r == '\\':
			return -1
		case r < 0x20 || r == 0x7f:
			return ' '
		}
		return r
	}, title)
	realm = strings.Join(strings.Fields(realm), " ")
	if realm == "" {
		realm = DefaultTitle
	}
	lit, _ := json.Marshal(realm) // a valid JS string literal; cannot fail
	return strings.Replace(workerJS, "__REALM__", string(lit), 1)
}

// syncCloudflareAuth writes the worker when enabled, and otherwise removes
// one left by an earlier build, so that dropping the flag never silently
// keeps the gate. It also removes the functions/_middleware.js of earlier
// versions (and functions/ if that empties it) without reporting it. It
// returns "written", "removed" or "" when there was nothing to do.
func syncCloudflareAuth(outDir, title string, enabled bool) (string, error) {
	if err := removeLegacyMiddleware(outDir); err != nil {
		return "", err
	}
	path := filepath.Join(outDir, CloudflareWorker)
	if enabled {
		if err := os.MkdirAll(outDir, 0o755); err != nil {
			return "", fmt.Errorf("write %s: %w", CloudflareWorker, err)
		}
		if err := os.WriteFile(path, []byte(workerSource(title)), 0o644); err != nil {
			return "", fmt.Errorf("write %s: %w", CloudflareWorker, err)
		}
		return "written", nil
	}
	if err := os.Remove(path); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return "", nil
		}
		return "", fmt.Errorf("remove %s: %w", CloudflareWorker, err)
	}
	return "removed", nil
}

func removeLegacyMiddleware(outDir string) error {
	path := filepath.Join(outDir, filepath.FromSlash(legacyMiddleware))
	if err := os.Remove(path); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("remove %s: %w", legacyMiddleware, err)
	}
	dir := filepath.Dir(path)
	if entries, err := os.ReadDir(dir); err == nil && len(entries) == 0 {
		if err := os.Remove(dir); err != nil {
			return fmt.Errorf("remove %s: %w", filepath.Dir(legacyMiddleware), err)
		}
	}
	return nil
}
